#!/usr/bin/env python3
"""Regenerates Assets/_Game/Economy/HeroTable.cs from the hero generator output.

Inputs
  Tests/Simulation/hero_gen/heroes.csv  columns id,line,tier,launchTenths,speed,control,wall,fi15,mean75,maxdev,attempts,status
                                        only rows with status OK are used (the last OK row of an id wins). A missing or empty file is fine.
  Momo's ladder                         the five fixed tiers (HeroIndex.LadderFinal), hard-coded below.
  Assets/_Game/Economy/HeroTable.cs     heroes missing from the csv keep their rows from the existing file.

The output has exactly the format of the committed file, so running the script on an empty csv reproduces the table (after Momo's ladder is applied).
Usage:  python Tools/hero_table_gen.py [--csv PATH] [--out PATH] [--check]
        --check only compares and exits 1 when the file would change.

Per-player hero variants (owner 2026-11-12, docs/44 section 11): the same run also writes Assets/_Game/Economy/HeroVariants.cs from
  Tests/Simulation/hero_gen/variants.csv  columns id,variant,launchTenths,speed,control,wall,fi15,mean75,maxdev,attempt  (every row passed the measured FI gate; HeroVariantGeneratorTests, HERO_VAR=1)
Only the four upper tiers of the ACTIVE lines are emitted (Common stays fixed). --variants-csv / --variants-out override the paths; --check covers both files.
"""
import argparse
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CSV = os.path.join(ROOT, "Tests", "Simulation", "hero_gen", "heroes.csv")
DEFAULT_OUT = os.path.join(ROOT, "Assets", "_Game", "Economy", "HeroTable.cs")
DEFAULT_VCSV = os.path.join(ROOT, "Tests", "Simulation", "hero_gen", "variants.csv")
DEFAULT_VOUT = os.path.join(ROOT, "Assets", "_Game", "Economy", "HeroVariants.cs")

# Same order as TierRules.Lines (the order of the rows in the table).
LINES = ["momo", "forestgirl", "beachotter", "candygirl", "monk", "bumble", "ribbi", "dandy", "pip", "nib", "spike", "moss", "fenn",
         "pinch", "shelly", "bloop", "coco", "gummi", "choco", "marsh", "cookie", "sprout", "tora", "rusu", "ryu"]
# THE ONE LIST of active hero lines (owner 2026-11-09, Bug List 6): only these five lines exist at runtime (25 heroes). Every other line keeps its generated physics rows as DATA
# (Active = false) but is never in CharacterDefs.All, in any pool, shop, reward, save or screen. A permanent compile-time rule: no setting, no toggle.
ACTIVE_LINES = ["momo", "forestgirl", "beachotter", "candygirl", "monk"]
SUFFIX = ["", "_u", "_r", "_e", "_l"]
TIER_NAMES = {"common": 0, "uncommon": 1, "rare": 2, "elite": 3, "epic": 3, "legendary": 4}

# HeroIndex.LadderFinal: launch tenths, speed, control, wall.
MOMO_LADDER = [(190, 9, 30, 77), (209, 9, 34, 82), (216, 9, 38, 88), (219, 10, 41, 94), (228, 11, 41, 100)]

ROW_RE = re.compile(r'new HeroRow\("([^"]+)", "([^"]+)", (\d+), (\d+), (\d+), (\d+), (\d+)(?:, (?:true|false))?\)')
LEGACY_RE = re.compile(r'Legacy =\s*\{(.*?)\};', re.S)

HEADER = """// GENERATED by Tools/hero_table_gen.py from Tests/Simulation/hero_gen/heroes.csv (status OK rows) and Momo's ladder (HeroIndex.LadderFinal). Do not edit by hand.
// One row per hero: the four physics numbers (launch in TENTHS of u/s, 190 = 19.0; speed; control; wall bounce share in hundredths). Tier 0 Common .. 4 Legendary.
// Rows listed in Legacy still carry the old hand-tuned stats (converted 1:1) and are not yet generated/measured; the generator removes an id from Legacy when it writes its row.
using System.Collections.Generic;

namespace FluffyClimbers.Economy
{
    /// <summary>The physics of one hero (docs/44, HeroIndex): plain data.</summary>
    public sealed class HeroRow
    {
        public readonly string Id, Line;
        public readonly int Tier, LaunchTenths, Speed, Control, Wall;
        /// <summary>True for the 25 heroes of the five active lines (<see cref="HeroTable.ActiveLines"/>). Inactive rows are data only: the hero never exists at runtime.</summary>
        public readonly bool Active;
        public HeroRow(string id, string line, int tier, int launchTenths, int speed, int control, int wall, bool active = true)
        {
            Id = id; Line = line; Tier = tier; LaunchTenths = launchTenths; Speed = speed; Control = control; Wall = wall; Active = active;
        }
    }

    public static class HeroTable
    {
        /// <summary>Id suffix per tier: the Common hero is the line id, the tiers add _u, _r, _e, _l.</summary>
        public static readonly string[] TierSuffix = { "", "_u", "_r", "_e", "_l" };

        /// <summary>THE ONE LIST of active hero lines (from ACTIVE_LINES in Tools/hero_table_gen.py): only these five lines (25 heroes) exist at runtime. A permanent compile-time rule, no setting.</summary>
        public static readonly string[] ActiveLines = { %ACTIVE% };

        /// <summary>True when the line is one of the five active lines.</summary>
        public static bool IsActiveLine(string line)
        {
            return System.Array.IndexOf(ActiveLines, line) >= 0;
        }

        /// <summary>Every row (all 125, active and inactive): the DATA accessor for tools and the bot proof tests. Runtime code uses CharacterDefs.All (active heroes only).</summary>
        public static readonly HeroRow[] Rows =
        {
"""

FOOTER = """        };

        static readonly Dictionary<string, HeroRow> ById = BuildIndex();

        static Dictionary<string, HeroRow> BuildIndex()
        {
            var d = new Dictionary<string, HeroRow>(Rows.Length);
            foreach (HeroRow r in Rows) d[r.Id] = r;
            return d;
        }

        /// <summary>The row of a hero id, or null.</summary>
        public static HeroRow Find(string id)
        {
            HeroRow r;
            return id != null && ById.TryGetValue(id, out r) ? r : null;
        }

        /// <summary>The row of a line at a tier (0 Common .. 4 Legendary), or null.</summary>
        public static HeroRow Of(string line, int tier)
        {
            if (line == null || tier < 0 || tier >= TierSuffix.Length) return null;
            return Find(line + TierSuffix[tier]);
        }

        /// <summary>True while the hero still has its old hand-tuned stats (not yet generated and measured).</summary>
        public static bool IsLegacy(string id)
        {
            return System.Array.IndexOf(Legacy, id) >= 0;
        }
    }
}
"""


def hero_id(line, tier):
    return line + SUFFIX[tier]


def read_existing(path):
    rows, legacy = {}, []
    if not os.path.exists(path):
        return rows, legacy
    text = open(path, encoding="utf-8").read()
    for m in ROW_RE.finditer(text):
        rows[m.group(1)] = (m.group(2), int(m.group(3)), int(m.group(4)), int(m.group(5)), int(m.group(6)), int(m.group(7)))
    m = LEGACY_RE.search(text)
    if m:
        legacy = re.findall(r'"([^"]+)"', m.group(1))
    return rows, legacy


def read_csv(path):
    out = {}
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return out
    with open(path, newline="", encoding="utf-8") as f:
        for rec in csv.DictReader(f):
            if (rec.get("status") or "").strip().upper() != "OK":
                continue
            t = (rec["tier"] or "").strip()
            tier = int(t) if t.isdigit() else TIER_NAMES[t.lower()]
            line = rec["line"].strip()
            out[rec["id"].strip()] = (line, tier, int(rec["launchTenths"]), int(rec["speed"]), int(rec["control"]), int(rec["wall"]))
    return out


def build(existing_rows, existing_legacy, csv_rows):
    rows, legacy = [], []
    for line in LINES:
        for tier in range(5):
            hid = hero_id(line, tier)
            if line == "momo":
                row = (line, tier) + MOMO_LADDER[tier]
            elif hid in csv_rows:
                row = csv_rows[hid]
            elif hid in existing_rows:
                row = existing_rows[hid]
                if hid in existing_legacy:
                    legacy.append(hid)
            else:
                raise SystemExit("no stats for hero " + hid + ": not in the csv and not in the existing table")
            rows.append((hid,) + row)
    return rows, legacy


def emit(rows, legacy):
    parts = [HEADER.replace("%ACTIVE%", ", ".join('"%s"' % x for x in ACTIVE_LINES))]
    last_line = None
    for hid, line, tier, launch, speed, control, wall in rows:
        if line != last_line:
            if last_line is not None:
                parts.append("\n")
            parts.append("            // " + line + "\n")
            last_line = line
        parts.append('            new HeroRow("%s", "%s", %d, %d, %d, %d, %d, %s),\n' % (hid, line, tier, launch, speed, control, wall, "true" if line in ACTIVE_LINES else "false"))
    parts.append(FOOTER.split("        };\n", 1)[0] + "        };\n\n")
    parts.append("        /// <summary>Hero ids that still carry the old hand-tuned stats (not yet generated and measured).</summary>\n")
    parts.append("        public static readonly string[] Legacy =\n        {\n")
    for i in range(0, len(legacy), 8):
        parts.append("            " + ", ".join('"%s"' % x for x in legacy[i:i + 8]) + ",\n")
    parts.append("        };\n")
    parts.append(FOOTER.split("        };\n", 1)[1])
    return "".join(parts)


def read_variants(path):
    """id -> list of (launch, speed, control, wall) in file order (variant number order), deduplicated; only active tier heroes."""
    out = {}
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return out
    valid = set(hero_id(l, t) for l in ACTIVE_LINES for t in range(1, 5))
    with open(path, newline="", encoding="utf-8") as f:
        for rec in csv.DictReader(f):
            hid = rec["id"].strip()
            if hid not in valid:
                continue
            row = (int(rec["launchTenths"]), int(rec["speed"]), int(rec["control"]), int(rec["wall"]))
            lst = out.setdefault(hid, [])
            if row not in lst:
                lst.append(row)
    return out


VARIANTS_HEADER = """// GENERATED by Tools/hero_table_gen.py from Tests/Simulation/hero_gen/variants.csv. Do not edit by hand.
// The per-player hero variant pool (owner 2026-11-12, docs/44 section 11): for every tier hero (Uncommon .. Legendary) of the active lines, the extra physics rows that passed the measured
// Forgiveness Index gate. The pool of a hero is its HeroTable row (variant 0) followed by its rows here (variants 1..). Common heroes have no variants. See Economy/HeroRolls.cs.
namespace FluffyClimbers.Economy
{
    public static class HeroVariants
    {
        /// <summary>Variant rows, grouped by hero id, in variant order. The four physics numbers (launch tenths, speed, control, wall hundredths) as in <see cref="HeroTable"/>.</summary>
        public static readonly HeroRow[] Rows =
        {
"""
VARIANTS_FOOTER = """        };
    }
}
"""


def emit_variants(variants):
    parts = [VARIANTS_HEADER]
    for line in ACTIVE_LINES:
        for tier in range(1, 5):
            hid = hero_id(line, tier)
            for (l, sp, c, w) in variants.get(hid, []):
                parts.append('            new HeroRow("%s", "%s", %d, %d, %d, %d, %d, true),\n' % (hid, line, tier, l, sp, c, w))
    parts.append(VARIANTS_FOOTER)
    return "".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=DEFAULT_CSV)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--variants-csv", default=DEFAULT_VCSV)
    ap.add_argument("--variants-out", default=DEFAULT_VOUT)
    ap.add_argument("--seed", help="JSON file {id: [line,tier,launchTenths,speed,control,wall]} used instead of the existing table (first creation only)")
    a = ap.parse_args()
    existing_rows, existing_legacy = read_existing(a.out)
    if a.seed:
        import json
        seed = json.load(open(a.seed))
        existing_rows = {k: tuple(v) for k, v in seed.items()}
        existing_legacy = [k for k in seed if not k.startswith("momo")]
    rows, legacy = build(existing_rows, existing_legacy, read_csv(a.csv))
    text = emit(rows, legacy)
    old = open(a.out, encoding="utf-8").read() if os.path.exists(a.out) else None
    vtext = emit_variants(read_variants(a.variants_csv))
    vold = open(a.variants_out, encoding="utf-8").read() if os.path.exists(a.variants_out) else None
    if a.check:
        sys.exit(0 if old == text and vold == vtext else 1)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("%d heroes, %d legacy -> %s" % (len(rows), len(legacy), a.out))
    with open(a.variants_out, "w", encoding="utf-8", newline="\n") as f:
        f.write(vtext)
    print("%d variant rows -> %s" % (vtext.count("new HeroRow("), a.variants_out))


if __name__ == "__main__":
    main()
