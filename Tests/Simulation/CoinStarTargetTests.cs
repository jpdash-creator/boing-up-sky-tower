using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.Json;
using Xunit;

namespace BoingUpSkyTower.Simulation.Tests
{
    /// <summary>
    /// T14: derives the star-2 coin targets of regions 1-5 from the bot and checks the shipped table.
    ///
    /// Rule (documented in Assets/_Game/Simulation/NOTES.md): target = max(oldTarget, floor(85 percent of the bot's
    /// proven coin lower bound, to a multiple of 5)); if that exceeds the bound it is capped to the bound (rounded down
    /// to a multiple of 5) and flagged "capped". oldTarget = 20 + 5 * levelIndex. The bound is the coins held when the
    /// run ends (the goal is met), see SolvabilityT4Tests.
    ///
    /// Re-run after any change to the builder, the bot, the physics or the speedrun time:
    ///   $env:UPDATE_COIN_TARGETS = "1"; dotnet test --filter FullyQualifiedName~CoinStarTargetTests
    /// then python Tools/content_cli/gen_content.py. Without the variable the tests only verify the shipped table
    /// (Content/config/coin_star_targets.json) against the content and the bot.
    /// </summary>
    public class CoinStarTargetTests
    {
        public const int PercentOfBound = 85;
        public const int RoundTo = 5;

        private static string TablePath(string root)
        {
            return Path.Combine(root, "Content", "config", "coin_star_targets.json");
        }

        public static int OldTarget(int levelIndex) { return 20 + 5 * levelIndex; }

        public static int TargetFor(int bound, int levelIndex, out bool capped)
        {
            int t = bound * PercentOfBound / 100 / RoundTo * RoundTo;
            int old = OldTarget(levelIndex);
            if (t < old) t = old;
            capped = false;
            if (t > bound) { t = bound / RoundTo * RoundTo; capped = true; }
            return t;
        }

        private static int StarCoinValue(LevelSpec spec)
        {
            for (int i = 0; i < spec.Stars.Length; i++) if (spec.Stars[i].Kind == StarSpec.KindCoins) return spec.Stars[i].Value;
            return 0;
        }

        private static int Bound(LevelOutcome o)
        {
            int bound = o.Solve.Coins;
            if (o.CoinSearchRan && o.CoinSearch.Solved && o.CoinSearch.Coins > bound) bound = o.CoinSearch.Coins;
            return bound;
        }

        private static bool Updating { get { return Environment.GetEnvironmentVariable("UPDATE_COIN_TARGETS") == "1"; } }

        private static void WriteTable(string root, List<LevelOutcome> list)
        {
            StringBuilder sb = new StringBuilder();
            sb.Append("{\n");
            sb.Append("  \"_doc\": \"Generated by Tests/Simulation CoinStarTargetTests (UPDATE_COIN_TARGETS=1). Do not edit by hand. target = max(oldTarget, floor(percentOfBotBound percent of botBound to a multiple of roundTo)), capped at botBound.\",\n");
            sb.Append("  \"percentOfBotBound\": ").Append(PercentOfBound).Append(",\n");
            sb.Append("  \"roundTo\": ").Append(RoundTo).Append(",\n");
            sb.Append("  \"levels\": {\n");
            for (int i = 0; i < list.Count; i++)
            {
                LevelOutcome o = list[i];
                bool capped;
                int bound = Bound(o);
                int target = TargetFor(bound, o.Level.Spec.LevelIndex, out capped);
                sb.Append("    \"").Append(o.Level.Id).Append("\": {\"target\": ").Append(target)
                  .Append(", \"botBound\": ").Append(bound)
                  .Append(", \"oldTarget\": ").Append(OldTarget(o.Level.Spec.LevelIndex))
                  .Append(", \"capped\": ").Append(capped ? "true" : "false").Append("}")
                  .Append(i + 1 < list.Count ? ",\n" : "\n");
            }
            sb.Append("  }\n}\n");
            File.WriteAllText(TablePath(root), sb.ToString(), new UTF8Encoding(false));
        }

        [Fact]
        public void NoShippedLevelHasATimedGoal()
        {
            string root = ContentLoader.FindRoot();
            if (root == null) return;
            foreach (LevelOutcome o in SolvabilityT4Tests.Outcomes())
                Assert.NotEqual(GoalType.Speedrun, o.Level.Spec.Goal.Type);
        }
    }
}
